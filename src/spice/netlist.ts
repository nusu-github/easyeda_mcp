import { createHash } from "node:crypto";
import type { SchematicComponent, SchematicPin, SchematicSnapshot } from "../schematic/analysis.js";
import type { LtspiceSymbol } from "./ltspiceSymbols.js";
import { DEFAULT_GROUND_NETS, resolvePart, ruleUnits, type MappingFile, type PartRule } from "./models.js";
import { isNotPopulated, parseComponentValue } from "./values.js";

export type SymbolLookup = { find(nameOrPath: string): Promise<LtspiceSymbol | undefined> };

export type SpiceExportOptions = {
  mapping: MappingFile;
  symbols: SymbolLookup;
  groundNets?: string[];
  title?: string;
  /** Turns a mapping `include` into the path written to the netlist. */
  resolveInclude?: (include: string) => string;
};

export type ComponentReport = {
  designator: string;
  status: "emitted" | "ignored" | "skipped" | "unresolved";
  matchedBy?: "attributes" | "mapping" | "default";
  matchKey?: string;
  kind?: PartRule["kind"];
  model?: string;
  value?: string;
  lcsc?: string;
  mpn?: string;
  verified?: boolean;
  lines?: string[];
  reason?: string;
  warnings?: string[];
};

export type SpiceExportResult = {
  ok: boolean;
  netlist: string;
  components: ComponentReport[];
  unresolved: ComponentReport[];
  unverified: string[];
  /** EasyEDA net name → SPICE node name. */
  nodes: Record<string, string>;
  groundNets: string[];
  warnings: string[];
  snapshotHash: string;
};

type PartGroup = {
  designator: string;
  components: SchematicComponent[];
  pins: Map<string, SchematicPin>;
  value?: string;
  lcsc?: string;
  mpn?: string;
  name?: string;
  attributes: Record<string, string>;
};

const NON_PART_TYPES = new Set(["netflag", "netport", "short_symbol", "netlabel", "sheet", "drawing", "text"]);
const MODEL_PORTS: Record<string, string[]> = {
  D: ["A", "K"],
  Q: ["C", "B", "E"],
  M: ["D", "G", "S"],
  J: ["D", "G", "S"]
};

export async function buildSpiceNetlist(snapshot: SchematicSnapshot, options: SpiceExportOptions): Promise<SpiceExportResult> {
  const warnings: string[] = [];
  const groundNets = options.groundNets ?? options.mapping.groundNets ?? DEFAULT_GROUND_NETS;
  const nodes = new NodeNamer(groundNets);
  const groups = groupParts(snapshot, warnings);
  const reports: ComponentReport[] = [];
  const libraries = new Set<string>();
  const resolveInclude = options.resolveInclude ?? ((include: string) => include);

  for (const group of groups) {
    const base: ComponentReport = {
      designator: group.designator,
      status: "unresolved",
      value: group.value,
      lcsc: group.lcsc,
      mpn: group.mpn
    };

    if (isNotPopulated(group.value) || group.attributes.SPICE_Kind?.toLowerCase() === "dnp") {
      reports.push({ ...base, status: "skipped", reason: "Component is marked as not populated." });
      continue;
    }

    let resolution;
    try {
      resolution = resolvePart({
        designator: group.designator,
        lcsc: group.lcsc,
        mpn: group.mpn,
        name: group.name,
        attributes: group.attributes
      }, options.mapping);
    } catch (error) {
      reports.push({ ...base, reason: (error as Error).message });
      continue;
    }

    if (resolution.status === "ignored") {
      reports.push({ ...base, status: "ignored", matchedBy: resolution.matchedBy, reason: resolution.reason });
      continue;
    }
    if (resolution.status === "unresolved") {
      reports.push({ ...base, reason: resolution.reason });
      continue;
    }

    const { rule } = resolution;
    const report: ComponentReport = {
      ...base,
      matchedBy: resolution.matchedBy,
      matchKey: resolution.matchKey,
      kind: rule.kind,
      model: rule.model,
      verified: rule.verified
    };

    try {
      const emitted = await emitPart(group, rule, nodes, options.symbols);
      report.status = "emitted";
      report.lines = emitted.lines;
      if (emitted.warnings.length > 0) report.warnings = emitted.warnings;
      const include = rule.include ?? emitted.defaultInclude;
      if (include) libraries.add(resolveInclude(include));
    } catch (error) {
      report.status = "unresolved";
      report.reason = (error as Error).message;
    }
    reports.push(report);
  }

  if (!nodes.usedGround) {
    warnings.push(`No ground net (${groundNets.join(", ")}) is connected to an emitted part; the test bench must define node 0.`);
  }

  const unresolved = reports.filter((report) => report.status === "unresolved");
  const unverified = reports
    .filter((report) => report.status === "emitted" && report.verified === false)
    .map((report) => report.designator);
  const snapshotHash = hashSnapshot(groups);
  const netlist = [
    `* ${options.title ?? "DUT netlist"} — generated by easyeda-pro-mcp`,
    `* snapshot ${snapshotHash}`,
    "* Do not edit by hand: regenerate with easyeda_export_spice.",
    ...[...libraries].sort().map((library) => `.lib ${quotePath(library)}`),
    ...reports.flatMap((report) => report.lines ?? [])
  ].join("\n") + "\n";

  return {
    ok: unresolved.length === 0,
    netlist,
    components: reports,
    unresolved,
    unverified,
    nodes: nodes.mapping(),
    groundNets,
    warnings: [...warnings, ...nodes.warnings],
    snapshotHash
  };
}

async function emitPart(
  group: PartGroup,
  rule: PartRule,
  nodes: NodeNamer,
  symbols: SymbolLookup
): Promise<{ lines: string[]; warnings: string[]; defaultInclude?: string }> {
  const warnings: string[] = [];
  const params = rule.params ? ` ${rule.params}` : "";

  if (rule.kind === "primitive" || rule.kind === "short") {
    const pinNumbers = sortedPinNumbers(group);
    if (pinNumbers.length !== 2) {
      throw new Error(`${rule.kind} ${group.designator} needs exactly 2 pins, found ${pinNumbers.length}.`);
    }
    const [a, b] = pinNumbers.map((pin) => nodes.nodeFor(group, pin));
    if (rule.kind === "short") {
      return { lines: [`V${safeName(group.designator)}_short ${a} ${b} 0`], warnings };
    }
    const prefix = rule.prefix ?? group.designator[0]?.toUpperCase();
    const parsed = parseComponentValue(group.value);
    if (!parsed) {
      throw new Error(`Cannot parse value "${group.value ?? ""}" of ${group.designator} as a number.`);
    }
    if (parsed.value === 0 && prefix === "R") {
      return { lines: [`V${safeName(group.designator)}_short ${a} ${b} 0 ; 0 ohm`], warnings };
    }
    return { lines: [`${instanceName(prefix, group.designator)} ${a} ${b} ${parsed.spice}${params}`], warnings };
  }

  if (!rule.model) {
    throw new Error(`${rule.kind} ${group.designator} needs a model name.`);
  }

  if (rule.kind === "model") {
    const prefix = rule.prefix;
    if (!prefix || !MODEL_PORTS[prefix]) {
      throw new Error(`model ${group.designator} needs prefix D, Q, M or J.`);
    }
    const ports = MODEL_PORTS[prefix];
    const units = ruleUnits(rule);
    if (units.length !== 1) {
      throw new Error(`model ${group.designator} needs exactly one pinMap.`);
    }
    const ordered = mapPorts(group, ports, units[0], nodes);
    checkUnmappedPins(group, units, rule.ignorePins, warnings);
    const nodeList = prefix === "M" ? [...ordered, ordered[2]] : ordered;
    return { lines: [`${instanceName(prefix, group.designator)} ${nodeList.join(" ")} ${rule.model}${params}`], warnings };
  }

  // subckt
  let ports = rule.ports;
  let defaultInclude: string | undefined;
  if (!ports) {
    const symbol = await symbols.find(rule.symbol ?? rule.model);
    if (!symbol || symbol.ports.length === 0) {
      throw new Error(`Port order for ${rule.model} is unknown: no LTspice symbol "${rule.symbol ?? rule.model}" with SpiceOrder, and no "ports" in the mapping.`);
    }
    ports = symbol.ports;
    defaultInclude = symbol.spiceModel;
  }
  const units = ruleUnits(rule);
  if (units.length === 0) {
    throw new Error(`subckt ${group.designator} needs pinMap or units.`);
  }
  const lines = units.map((pinMap, index) => {
    const ordered = mapPorts(group, ports, pinMap, nodes);
    const suffix = units.length > 1 ? String.fromCharCode(65 + index) : "";
    return `X${safeName(group.designator)}${suffix} ${ordered.join(" ")} ${rule.model}${params}`;
  });
  checkUnmappedPins(group, units, rule.ignorePins, warnings);
  return { lines, warnings, defaultInclude };
}

function mapPorts(group: PartGroup, ports: string[], pinMap: Record<string, string>, nodes: NodeNamer): string[] {
  const byPort = new Map<string, string>();
  for (const [pin, port] of Object.entries(pinMap)) {
    const match = ports.find((candidate) => candidate.toLowerCase() === port.toLowerCase());
    if (!match) {
      throw new Error(`${group.designator}: pinMap uses port "${port}", which is not one of ${ports.join(", ")}.`);
    }
    if (byPort.has(match)) {
      throw new Error(`${group.designator}: port "${match}" is mapped twice (pins ${byPort.get(match)} and ${pin}).`);
    }
    if (!group.pins.has(pin)) {
      throw new Error(`${group.designator}: pinMap uses pin ${pin}, which the EasyEDA symbol does not have (pins: ${sortedPinNumbers(group).join(", ")}).`);
    }
    byPort.set(match, pin);
  }
  const missing = ports.filter((port) => !byPort.has(port));
  if (missing.length > 0) {
    throw new Error(`${group.designator}: ports ${missing.join(", ")} are not mapped to any pin.`);
  }
  return ports.map((port) => nodes.nodeFor(group, byPort.get(port)!));
}

function checkUnmappedPins(group: PartGroup, units: Array<Record<string, string>>, ignorePins: string[] | undefined, warnings: string[]): void {
  const mapped = new Set(units.flatMap((unit) => Object.keys(unit)));
  const ignored = new Set(ignorePins ?? []);
  const connected: string[] = [];
  for (const [number, pin] of group.pins) {
    if (mapped.has(number) || ignored.has(number)) continue;
    if (pin.net || pin.nodeId) {
      connected.push(number);
    } else {
      warnings.push(`Pin ${number} of ${group.designator} is unmapped and unconnected; ignored.`);
    }
  }
  if (connected.length > 0) {
    throw new Error(`${group.designator}: pins ${connected.join(", ")} are connected but not in pinMap; map them or list them in ignorePins.`);
  }
}

function groupParts(snapshot: SchematicSnapshot, warnings: string[]): PartGroup[] {
  const pinsByComponent = new Map<string, SchematicPin[]>();
  for (const pin of snapshot.pins) {
    if (!pin.componentPrimitiveId) continue;
    const list = pinsByComponent.get(pin.componentPrimitiveId) ?? [];
    list.push(pin);
    pinsByComponent.set(pin.componentPrimitiveId, list);
  }

  const groups = new Map<string, PartGroup>();
  for (const component of snapshot.components) {
    const type = component.componentType?.toLowerCase();
    if (type && NON_PART_TYPES.has(type)) continue;
    const pins = component.primitiveId ? pinsByComponent.get(component.primitiveId) ?? [] : [];
    if (!component.designator || (type !== "part" && pins.length === 0)) continue;

    const group = groups.get(component.designator) ?? {
      designator: component.designator,
      components: [],
      pins: new Map<string, SchematicPin>(),
      attributes: {}
    };
    group.components.push(component);
    group.value ??= component.value;
    group.lcsc ??= component.supplierId ?? rawString(component.raw, "supplierId");
    group.mpn ??= component.manufacturerId;
    group.name ??= component.name;
    group.attributes = { ...(component.attributes ?? rawAttributes(component.raw)), ...group.attributes };

    for (const pin of pins) {
      if (!pin.pinNumber) continue;
      const existing = group.pins.get(pin.pinNumber);
      if (!existing || (!existing.net && !existing.nodeId)) {
        group.pins.set(pin.pinNumber, pin);
      } else if ((pin.net || pin.nodeId) && (pin.net ?? pin.nodeId) !== (existing.net ?? existing.nodeId)) {
        warnings.push(`${component.designator} pin ${pin.pinNumber} appears in several sub-parts on different nets (${existing.net ?? existing.nodeId} vs ${pin.net ?? pin.nodeId}); using the first.`);
      }
    }
    groups.set(component.designator, group);
  }
  return [...groups.values()].sort((left, right) => compareDesignators(left.designator, right.designator));
}

class NodeNamer {
  private readonly ground: Set<string>;
  private readonly byKey = new Map<string, string>();
  private readonly used = new Set<string>(["0"]);
  private readonly netNames = new Map<string, string>();
  private anonymous = 0;
  readonly warnings: string[] = [];
  usedGround = false;

  constructor(groundNets: string[]) {
    this.ground = new Set(groundNets.map((net) => net.toLowerCase()));
  }

  nodeFor(group: PartGroup, pinNumber: string): string {
    const pin = group.pins.get(pinNumber);
    if (pin?.net) {
      return this.named(pin.net);
    }
    if (pin?.nodeId) {
      const key = `id:${pin.nodeId}`;
      let node = this.byKey.get(key);
      if (!node) {
        node = this.unique(`N${String(++this.anonymous).padStart(3, "0")}`);
        this.byKey.set(key, node);
      }
      return node;
    }
    const node = this.unique(`NC_${safeName(group.designator)}_${safeName(pinNumber)}`);
    this.warnings.push(`${group.designator} pin ${pinNumber} has no connection; it is left floating as ${node}.`);
    return node;
  }

  mapping(): Record<string, string> {
    return Object.fromEntries([...this.netNames.entries()].sort(([a], [b]) => a.localeCompare(b)));
  }

  private named(net: string): string {
    if (this.ground.has(net.toLowerCase())) {
      this.usedGround = true;
      this.netNames.set(net, "0");
      return "0";
    }
    const key = `net:${net.toLowerCase()}`;
    let node = this.byKey.get(key);
    if (!node) {
      node = this.unique(safeName(net));
      this.byKey.set(key, node);
      this.netNames.set(net, node);
    }
    return node;
  }

  private unique(base: string): string {
    let candidate = base || "N";
    let index = 1;
    while (this.used.has(candidate.toLowerCase())) {
      candidate = `${base}_${++index}`;
    }
    this.used.add(candidate.toLowerCase());
    return candidate;
  }
}

function instanceName(prefix: string, designator: string): string {
  const safe = safeName(designator);
  return safe.toUpperCase().startsWith(prefix.toUpperCase()) ? safe : `${prefix}${safe}`;
}

function safeName(text: string): string {
  return text.replace(/^\+/, "P").replace(/^-/, "N").replace(/[^A-Za-z0-9_]/g, "_");
}

function quotePath(file: string): string {
  return /[\s;]/.test(file) ? `"${file}"` : file;
}

function sortedPinNumbers(group: PartGroup): string[] {
  return [...group.pins.keys()].sort(compareDesignators);
}

function compareDesignators(left: string, right: string): number {
  return left.localeCompare(right, undefined, { numeric: true, sensitivity: "base" });
}

function hashSnapshot(groups: PartGroup[]): string {
  const canonical = groups.map((group) => [
    group.designator,
    group.value ?? "",
    group.lcsc ?? "",
    Object.entries(group.attributes).filter(([key]) => key.startsWith("SPICE_")).sort(),
    [...group.pins.entries()].map(([number, pin]) => [number, pin.net ?? pin.nodeId ?? ""]).sort()
  ]);
  return createHash("sha256").update(JSON.stringify(canonical)).digest("hex").slice(0, 16);
}

function rawString(raw: unknown, key: string): string | undefined {
  const value = raw && typeof raw === "object" ? (raw as Record<string, unknown>)[key] : undefined;
  return typeof value === "string" && value.trim() ? value.trim() : undefined;
}

function rawAttributes(raw: unknown): Record<string, string> {
  const record = raw && typeof raw === "object" ? (raw as Record<string, unknown>).otherProperty : undefined;
  const output: Record<string, string> = {};
  if (record && typeof record === "object") {
    for (const [key, value] of Object.entries(record as Record<string, unknown>)) {
      if (typeof value === "string" || typeof value === "number" || typeof value === "boolean") output[key] = String(value);
    }
  }
  return output;
}
